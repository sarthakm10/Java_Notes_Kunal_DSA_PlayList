-- V3: optimistic locking, an activity log, and more tasks so paging has something to page.

ALTER TABLE task ADD COLUMN version BIGINT NOT NULL DEFAULT 0;     -- @Version counter

CREATE TABLE activity_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message    VARCHAR(200) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL
);

-- 8 backlog tasks in project 1 (ids 5-12): due 2026-11-11 .. 2026-11-18, the first two done
INSERT INTO task (project_id, assignee_id, title, priority, done, due_date, created_at, created_by)
SELECT 1,
       CASE WHEN n % 3 = 0 THEN NULL WHEN n % 2 = 0 THEN 2 ELSE 3 END,   -- ravi, meera or nobody
       'Backlog item ' || n,
       (ARRAY['LOW', 'MEDIUM', 'HIGH'])[n % 3 + 1],
       n <= 2,
       DATE '2026-11-10' + n,
       TIMESTAMPTZ '2026-10-24T09:00:00Z' + n * INTERVAL '1 day',
       'asha'
FROM generate_series(1, 8) AS n;

INSERT INTO task_tag (task_id, tag_id)
SELECT id, 1 FROM task WHERE title IN ('Backlog item 2', 'Backlog item 5');      -- tag them "backend"
